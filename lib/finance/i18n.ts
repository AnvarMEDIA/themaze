const DICTS: Record<FinLang, Dict> = { en, ru }

const MONTHS: Record<FinLang, string[]> = {
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
  ru: ['Янв', 'Фев', 'Мар', 'Апр', 'Май', 'Июн', 'Июл', 'Авг', 'Сен', 'Окт', 'Ноя', 'Дек'],
}

export function monthShort(lang: FinLang, monthIndex0: number): string {
  return MONTHS[lang][monthIndex0] ?? ''
}

/** Translate a key with optional {var} interpolation. Falls back en → key. */
export function translate(lang: FinLang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key
  if (vars) {
    // replaceAll, not replace — a placeholder may legitimately appear more
    // than once in a sentence, and a stray "{list}" would render to the user.
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}
